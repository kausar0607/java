public class Task9 {
    public static void main(String[] args) {
        double degree = 45;
        double radian = Math.toRadians(degree);

        System.out.println("Sin(45): " + Math.sin(radian));
        System.out.println("Cos(45): " + Math.cos(radian));
        System.out.println("Tan(45): " + Math.tan(radian));
    }
}